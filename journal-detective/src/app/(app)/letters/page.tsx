import Link from "next/link";
import { requireUser } from "@/lib/auth/session";
import { getT } from "@/lib/i18n/server";
import { prisma } from "@/lib/db";
import { PageHeader, Card } from "@/components/ui/card";
import { Pill } from "@/components/StatusBadge";
import { fmtDate } from "@/lib/utils";

export const dynamic = "force-dynamic";

export default async function Letters() {
  const user = await requireUser();
  const { lang, t } = await getT();
  const L = lang === "id";
  const letters = await prisma.letter.findMany({ where: user.role === "STUDENT" ? { application: { studentUserId: user.id }, status: { not: "DRAFT" } } : {}, include: { application: true }, orderBy: { updatedAt: "desc" } });
  return (
    <>
      <PageHeader title={t("nav.letters")} subtitle={L ? "Draf berwatermark hingga disetujui dan diterbitkan oleh Kepala Unit. Nomor surat resmi tidak pernah dibuat sistem." : "Watermarked drafts until approved and issued by the Head. Official letter numbers are never generated by the system."} />
      <Card><div className="overflow-x-auto"><table className="w-full">
        <thead><tr><th className="th">{L ? "Jenis" : "Type"}</th><th className="th">{L ? "Permohonan" : "Application"}</th><th className="th">{L ? "Nomor resmi" : "Official number"}</th><th className="th">Status</th><th className="th">{L ? "Diperbarui" : "Updated"}</th></tr></thead>
        <tbody className="divide-y divide-slate-100">{letters.map((l) => (
          <tr key={l.id} className="hover:bg-slate-50"><td className="td"><Link className="font-semibold text-navy-800 underline" href={`/letters/${l.id}`}>{t(`letter.${l.type}`)}</Link></td>
            <td className="td">{l.application.refNumber}<div className="text-xs text-slate-500">{l.application.studentName}</div></td><td className="td font-mono text-xs">{l.officialNumber ?? "—"}</td>
            <td className="td"><Pill tone={l.status === "ISSUED" ? "green" : l.status === "REVOKED" ? "red" : "amber"}>{t(`letter.${l.status}`)}</Pill></td><td className="td text-xs">{fmtDate(l.updatedAt, true)}</td></tr>))}
          {letters.length === 0 && <tr><td className="td text-slate-500" colSpan={5}>—</td></tr>}</tbody></table></div></Card>
    </>
  );
}
